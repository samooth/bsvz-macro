    return out.toOwnedSlice(allocator);
}

pub fn registerBoltMacros(table: *MacroTable) !void {
    try table.register("BOLT_SMB_LOCK_SUFFIX", .{ .arity = 0, .param_types = &.{}, .expand_fn = suffixExpand(&smb_lock_suffix) });
    try table.register("BOLT_SMB_UNLOCK_SUFFIX", .{ .arity = 0, .param_types = &.{}, .expand_fn = suffixExpand(&smb_unlock_suffix) });
    try table.register("BOLT_MS_LOCK_SUFFIX", .{ .arity = 0, .param_types = &.{}, .expand_fn = suffixExpand(&ms_lock_suffix) });
    const string_types = [_]ParamType{.string} ** 11;
    const ms_string_types = [_]ParamType{.string} ** 6;
    try table.register("BOLT_SMB_LOCK", .{ .arity = 11, .param_types = &string_types, .expand_fn = smbLockExpand });
    try table.register("BOLT_MS_LOCK", .{ .arity = 6, .param_types = &ms_string_types, .expand_fn = msLockExpand });
    try table.register("BOLT_P2P_LOCK", .{ .arity = 1, .param_types = &.{.string}, .expand_fn = p2pLockExpand });
    try table.register("BOLT_P2P_UNLOCK", .{ .arity = 2, .param_types = &.{ .string, .string }, .expand_fn = p2pUnlockExpand });
}

test "bolt: suffix bytes hash to b017 goldens" {
    const sha = std.crypto.hash.sha2.Sha256;
    var digest: [32]u8 = undefined;

    sha.hash(&smb_lock_suffix, &digest, .{});
    try std.testing.expectEqualStrings(golden_hashes.smb_lock, &std.fmt.bytesToHex(&digest, .lower));

    sha.hash(&smb_unlock_suffix, &digest, .{});
    try std.testing.expectEqualStrings(golden_hashes.smb_unlock, &std.fmt.bytesToHex(&digest, .lower));

    sha.hash(&ms_lock_suffix, &digest, .{});
    try std.testing.expectEqualStrings(golden_hashes.ms_lock, &std.fmt.bytesToHex(&digest, .lower));

    sha.hash(&ms_unlock_suffix, &digest, .{});
    try std.testing.expectEqualStrings(golden_hashes.ms_unlock, &std.fmt.bytesToHex(&digest, .lower));

    try std.testing.expectEqual(@as(usize, 5103), smb_lock_suffix.len);
    try std.testing.expectEqual(@as(usize, 414), smb_unlock_suffix.len);
    try std.testing.expectEqual(@as(usize, 1113), ms_lock_suffix.len);
    try std.testing.expectEqual(@as(usize, 414), ms_unlock_suffix.len);
    try std.testing.expectEqualSlices(u8, &smb_unlock_suffix, &ms_unlock_suffix);
}
