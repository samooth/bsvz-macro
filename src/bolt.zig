fn emitOpcode(out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator, op: Opcode) !void {
    try out.append(allocator, op.toByte());
}

fn hexCharVal(c: u8) u4 {
    return switch (c) {
        '0'...'9' => @intCast(c - '0'),
        'a'...'f' => @intCast(c - 'a' + 10),
        'A'...'F' => @intCast(c - 'A' + 10),
        else => 0,
    };
}

fn decodeHex(out: []u8, raw: []const u8) bool {
    var hex = raw;
    if (hex.len >= 2 and hex[0] == '0' and (hex[1] == 'x' or hex[1] == 'X')) hex = hex[2..];
    if ((hex.len % 2) != 0) return false;
    var i: usize = 0;
    while (i < hex.len) : (i += 2) {
        if (!std.ascii.isHex(hex[i]) or !std.ascii.isHex(hex[i + 1])) return false;
        out[i / 2] = (@as(u8, hexCharVal(hex[i])) << 4) | hexCharVal(hex[i + 1]);
    }
    return true;
}

fn hexByteLen(raw: []const u8) ?usize {
    var hex = raw;
    if (hex.len >= 2 and hex[0] == '0' and (hex[1] == 'x' or hex[1] == 'X')) hex = hex[2..];
    if ((hex.len % 2) != 0 or hex.len / 2 > 520) return null;
    for (hex) |c| if (!std.ascii.isHex(c)) return null;
    return hex.len / 2;
}

fn requireStringArg(arg: AstNode) ExpandError![]const u8 {
    if (arg != .string_literal) return ExpandError.TypeMismatch;
    return arg.string_literal;
}

fn emitPushHexString(out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator, raw: []const u8) ExpandError!void {
    const n = hexByteLen(raw) orelse return ExpandError.TypeMismatch;
    var buf: [520]u8 = undefined;
    if (!decodeHex(buf[0..n], raw)) return ExpandError.TypeMismatch;
    builder.appendPushData(out, allocator, buf[0..n]) catch return ExpandError.OutOfMemory;
}

fn emitSuffix(out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator, suffix: []const u8) ExpandError!void {
    try out.appendSlice(allocator, suffix);
}

fn suffixExpand(suffix: []const u8) fn (std.mem.Allocator, []const AstNode, ?[]const AstNode, *const MacroTable) ExpandError![]const u8 {
    return struct {
        const s = suffix;
        fn expand(allocator: std.mem.Allocator, args: []const AstNode, body: ?[]const AstNode, table: *const MacroTable) ExpandError![]const u8 {
            _ = args; _ = body; _ = table;
            var out: std.ArrayListUnmanaged(u8) = .empty;
            defer out.deinit(allocator);
            try emitSuffix(&out, allocator, s);
            return out.toOwnedSlice(allocator);
        }
    }.expand;
}

fn smbLockExpand(allocator: std.mem.Allocator, args: []const AstNode, body: ?[]const AstNode, table: *const MacroTable) ExpandError![]const u8 {
    _ = body; _ = table;
    if (args.len != 11) return ExpandError.ArityMismatch;
    var out: std.ArrayListUnmanaged(u8) = .empty;
    defer out.deinit(allocator);
    for (args) |arg| try emitPushHexString(&out, allocator, try requireStringArg(arg));
    try emitSuffix(&out, allocator, &smb_lock_suffix);
    return out.toOwnedSlice(allocator);
}

