fn p2pLockExpand(allocator: std.mem.Allocator, args: []const AstNode, body: ?[]const AstNode, table: *const MacroTable) ExpandError![]const u8 {
    _ = body; _ = table;
    if (args.len != 1) return ExpandError.ArityMismatch;
    var out: std.ArrayListUnmanaged(u8) = .empty;
    defer out.deinit(allocator);
    try emitPushHexString(&out, allocator, "0x02b017");
    try emitOpcode(&out, allocator, .OP_EQUALVERIFY);
    try emitOpcode(&out, allocator, .OP_DUP);
    try emitOpcode(&out, allocator, .OP_HASH160);
    try emitPushHexString(&out, allocator, try requireStringArg(args[0]));
    try emitOpcode(&out, allocator, .OP_EQUALVERIFY);
    try emitOpcode(&out, allocator, .OP_CHECKSIG);
    return out.toOwnedSlice(allocator);
}

fn p2pUnlockExpand(allocator: std.mem.Allocator, args: []const AstNode, body: ?[]const AstNode, table: *const MacroTable) ExpandError![]const u8 {
    _ = body; _ = table;
    if (args.len != 2) return ExpandError.ArityMismatch;
